func TestNewEntityID(t *testing.T) {
	id := NewEntityID("12345678-1234-9876-4563-123456789012", "example-resource-group", "healthmodelName", "entityName")

	if id.SubscriptionId != "12345678-1234-9876-4563-123456789012" {
		t.Fatalf("Expected %q but got %q for Segment 'SubscriptionId'", id.SubscriptionId, "12345678-1234-9876-4563-123456789012")
	}

	if id.ResourceGroupName != "example-resource-group" {
		t.Fatalf("Expected %q but got %q for Segment 'ResourceGroupName'", id.ResourceGroupName, "example-resource-group")
	}

	if id.HealthmodelName != "healthmodelName" {
		t.Fatalf("Expected %q but got %q for Segment 'HealthmodelName'", id.HealthmodelName, "healthmodelName")
	}

	if id.EntityName != "entityName" {
		t.Fatalf("Expected %q but got %q for Segment 'EntityName'", id.EntityName, "entityName")
	}
}

func TestFormatEntityID(t *testing.T) {
	actual := NewEntityID("12345678-1234-9876-4563-123456789012", "example-resource-group", "healthmodelName", "entityName").ID()
	expected := "/subscriptions/12345678-1234-9876-4563-123456789012/resourceGroups/example-resource-group/providers/Microsoft.CloudHealth/healthmodels/healthmodelName/entities/entityName"
	if actual != expected {
		t.Fatalf("Expected the Formatted ID to be %q but got %q", expected, actual)
	}
}

